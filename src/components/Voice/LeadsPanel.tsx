"use client";

import React, { useCallback, useEffect, useState } from "react";

interface Lead {
  id: string;
  name: string;
  phone: string;
  language: string;
  createdAt: string;
  customerType: string;
  loanType: string;
  amountRequired: string;
  monthlyIncome: string;
  existingObligations: string;
  employmentDetails: string;
  city: string;
  cibil: string;
  foir: string;
  intent: "Hot" | "Warm" | "Cold";
  score: number;
  summary: string;
  recommendedProducts: string[];
  nextAction: string;
  status?: "in_progress" | "qualified";
}

const INTENT_STYLE: Record<string, string> = {
  Hot: "bg-emerald-50 text-emerald-700 border-emerald-200",
  Warm: "bg-amber-50 text-amber-700 border-amber-200",
  Cold: "bg-slate-100 text-slate-600 border-slate-200",
};

function timeAgo(iso: string): string {
  if (!iso) return "";
  const then = new Date(iso).getTime();
  if (Number.isNaN(then)) return "";
  const mins = Math.max(0, Math.round((Date.now() - then) / 60000));
  if (mins < 1) return "just now";
  if (mins < 60) return `${mins} min ago`;
  const hours = Math.round(mins / 60);
  if (hours < 24) return `${hours} hr ago`;
  return new Date(iso).toLocaleDateString("en-IN", { day: "2-digit", month: "short" });
}

const LeadsPanel: React.FC = () => {
  const [leads, setLeads] = useState<Lead[]>([]);
  const [locked, setLocked] = useState(false);
  const [loading, setLoading] = useState(true);
  const [token, setToken] = useState("");
  const [expanded, setExpanded] = useState<string | null>(null);

  const load = useCallback(async (adminToken?: string) => {
    setLoading(true);
    try {
      const stored = adminToken ?? sessionStorage.getItem("voice-admin") ?? "";
      const res = await fetch("/api/voice/leads", {
        headers: stored ? { "x-voice-admin": stored } : undefined,
        cache: "no-store",
      });
      const data = (await res.json()) as { leads?: Lead[]; locked?: boolean };
      setLeads(data.leads ?? []);
      setLocked(Boolean(data.locked));
    } catch {
      setLeads([]);
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    load();
    const timer = setInterval(() => load(), 30000);
    return () => clearInterval(timer);
  }, [load]);

  const unlock = () => {
    sessionStorage.setItem("voice-admin", token.trim());
    load(token.trim());
  };

  return (
    <div className="mt-8 overflow-hidden rounded-2xl border border-LightSkyBlue bg-white shadow-darkmd dark:border-dark_border dark:bg-darkmode md:mt-10">
      <div className="flex flex-wrap items-center justify-between gap-3 border-b border-LightSkyBlue/70 px-5 py-4 dark:border-dark_border sm:px-6">
        <div>
          <h3 className="text-base font-bold text-secondary dark:text-white sm:text-lg">
            Leads generated by the AI
          </h3>
          <p className="mt-0.5 text-xs text-SlateBlueText dark:text-darktext">
            Analysed from call responses — customer profile, requirement, income and obligations.
            {leads.length > 0 ? ` Showing latest ${leads.length}.` : ""}
          </p>
        </div>
        <div className="flex items-center gap-2">
          <span className="rounded-full bg-primary/10 px-3 py-1 text-[11px] font-semibold text-primary">
            {loading ? "Loading…" : `${leads.length} lead${leads.length === 1 ? "" : "s"}`}
          </span>
          <button
            type="button"
            onClick={() => load()}
            className="rounded-lg border border-LightSkyBlue px-3 py-1.5 text-[11px] font-semibold text-SlateBlueText transition hover:border-primary hover:text-primary dark:border-dark_border dark:text-darktext"
          >
            Refresh
          </button>
        </div>
      </div>

      {locked ? (
        <div className="flex flex-col gap-3 px-5 py-6 sm:flex-row sm:items-end sm:px-6">
          <div className="flex-1">
            <label htmlFor="leads-token" className="mb-1.5 block text-xs font-semibold uppercase tracking-wide text-secondary dark:text-white/80">
              Admin key
            </label>
            <input
              id="leads-token"
              type="password"
              value={token}
              onChange={(event) => setToken(event.target.value)}
              placeholder="Enter VOICE_ADMIN_TOKEN"
              className="w-full rounded-lg border border-LightSkyBlue bg-white px-3.5 py-2.5 text-sm text-secondary outline-none focus:border-primary focus:ring-2 focus:ring-primary/20 dark:border-dark_border dark:bg-darklight dark:text-white"
            />
          </div>
          <button
            type="button"
            onClick={unlock}
            className="rounded-lg bg-primary px-5 py-2.5 text-sm font-semibold text-white transition hover:bg-RegalBlue"
          >
            Unlock
          </button>
        </div>
      ) : leads.length === 0 ? (
        <p className="px-5 py-8 text-center text-sm text-SlateBlueText dark:text-darktext sm:px-6">
          No calls captured yet. Place an AI call above — the analysis appears here as soon as the
          customer shares their requirement.
        </p>
      ) : (
        <ul className="divide-y divide-LightSkyBlue/60 dark:divide-dark_border">
          {leads.map((lead) => {
            const open = expanded === lead.id;
            return (
              <li key={lead.id || lead.phone}>
                <button
                  type="button"
                  onClick={() => setExpanded(open ? null : lead.id)}
                  aria-expanded={open}
                  className="grid w-full grid-cols-2 gap-x-4 gap-y-2 px-5 py-4 text-left transition hover:bg-IcyBreeze/50 dark:hover:bg-white/5 sm:px-6 lg:grid-cols-[1.2fr_1fr_1fr_1fr_auto]"
                >
                  <div className="min-w-0">
                    <p className="truncate text-sm font-semibold text-secondary dark:text-white">
                      {lead.name || "Unknown caller"}
                    </p>
                    <p className="truncate text-[11px] text-SlateBlueText dark:text-darktext">
                      {lead.phone} · {timeAgo(lead.createdAt)}
                    </p>
                  </div>

                  <div className="min-w-0">
                    <p className="truncate text-xs font-medium text-secondary dark:text-white/90">
                      {lead.loanType}
                    </p>
                    <p className="truncate text-[11px] text-SlateBlueText dark:text-darktext">
                      {lead.amountRequired} · {lead.customerType}
                    </p>
                  </div>

                  <div className="min-w-0">
                    <p className="truncate text-xs text-secondary dark:text-white/90">
                      {lead.monthlyIncome}
                    </p>
                    <p className="truncate text-[11px] text-SlateBlueText dark:text-darktext">
                      Obligations: {lead.existingObligations}
                    </p>
                  </div>

                  <div className="min-w-0">
                    <p className="truncate text-xs text-secondary dark:text-white/90">
                      FOIR {lead.foir}
                    </p>
                    <p className="truncate text-[11px] text-SlateBlueText dark:text-darktext">
                      {lead.city} · CIBIL {lead.cibil}
                    </p>
                  </div>

                  <div className="col-span-2 flex items-center justify-between gap-2 lg:col-span-1 lg:justify-end">
                    {lead.status === "in_progress" ? (
                      <span className="rounded-full border border-amber-200 bg-amber-50 px-2 py-0.5 text-[10px] font-semibold text-amber-700">
                        Capturing…
                      </span>
                    ) : null}
                    <span
                      className={`rounded-full border px-2.5 py-0.5 text-[10px] font-bold uppercase tracking-wide ${
                        INTENT_STYLE[lead.intent] ?? INTENT_STYLE.Cold
                      }`}
                    >
                      {lead.intent} · {lead.score}
                    </span>
                    <svg
                      className={`h-4 w-4 shrink-0 text-SlateBlueText transition ${open ? "rotate-180" : ""}`}
                      viewBox="0 0 20 20"
                      fill="currentColor"
                      aria-hidden="true"
                    >
                      <path
                        fillRule="evenodd"
                        d="M5.23 7.21a.75.75 0 011.06.02L10 11.17l3.71-3.94a.75.75 0 111.08 1.04l-4.25 4.5a.75.75 0 01-1.08 0l-4.25-4.5a.75.75 0 01.02-1.06z"
                        clipRule="evenodd"
                      />
                    </svg>
                  </div>
                </button>

                {open ? (
                  <div className="space-y-3 bg-IcyBreeze/40 px-5 pb-5 pt-1 dark:bg-white/5 sm:px-6">
                    <dl className="grid gap-3 text-xs sm:grid-cols-2 lg:grid-cols-3">
                      <div>
                        <dt className="font-semibold text-secondary dark:text-white/80">Occupation</dt>
                        <dd className="text-SlateBlueText dark:text-darktext">{lead.employmentDetails}</dd>
                      </div>
                      <div>
                        <dt className="font-semibold text-secondary dark:text-white/80">Requirement</dt>
                        <dd className="text-SlateBlueText dark:text-darktext">
                          {lead.loanType} — {lead.amountRequired}
                        </dd>
                      </div>
                      <div>
                        <dt className="font-semibold text-secondary dark:text-white/80">Repayment capacity</dt>
                        <dd className="text-SlateBlueText dark:text-darktext">
                          {lead.monthlyIncome} income · {lead.existingObligations} · FOIR {lead.foir}
                        </dd>
                      </div>
                    </dl>

                    <p className="text-xs leading-6 text-SlateBlueText dark:text-darktext">{lead.summary}</p>

                    {lead.recommendedProducts.length ? (
                      <p className="text-xs text-SlateBlueText dark:text-darktext">
                        <span className="font-semibold text-secondary dark:text-white/80">Suggested fit: </span>
                        {lead.recommendedProducts.join(" · ")}
                      </p>
                    ) : null}

                    <p className="text-xs text-SlateBlueText dark:text-darktext">
                      <span className="font-semibold text-secondary dark:text-white/80">Next step: </span>
                      {lead.nextAction}
                    </p>
                  </div>
                ) : null}
              </li>
            );
          })}
        </ul>
      )}

      <p className="border-t border-LightSkyBlue/70 px-5 py-3 text-[11px] leading-5 text-SlateBlueText dark:border-dark_border dark:text-darktext sm:px-6">
        Contact numbers are masked by default. Set <code className="font-mono">VOICE_ADMIN_TOKEN</code>{" "}
        in the environment to require a key for full details.
      </p>
    </div>
  );
};

export default LeadsPanel;
